import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

/**
 * Bundles the server into one file, and the panel into one HTML document.
 *
 * esbuild rather than `tsc`, and this is the first package here that needs a build at all,
 * so the reason is worth stating. Every other package ships raw TypeScript: its `exports`
 * point at `./src/*.ts` and the consumer — Next.js — compiles it. That works because the
 * consumer is a bundler. This package's consumer is `node`, launched as a child process by
 * an editor that knows nothing about pnpm workspaces, so emitted JavaScript still importing
 * `@terrablox/catalogue` would resolve to nothing. Bundling turns the workspace graph into
 * one file with no runtime dependencies, which is also what makes `npx terrablox-mcp`
 * possible outside this repo.
 *
 * The panel is inlined rather than served, for the same reason from the other direction: a
 * `ui://` resource is one HTML string handed to the host over `resources/read`. There is no
 * origin it could load a second file from.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "src");

/** The panel: its script bundled and inlined into the shell, as a committed TS module. */
async function buildUi() {
  const bundled = await build({
    bundle: true,
    entryPoints: [path.join(src, "ui/app.ts")],
    format: "esm",
    // The iframe is created by the host and could be any browser; these are the floors
    // that carry `replaceChildren` and top-level `await` without a polyfill.
    target: ["es2022", "chrome111", "firefox111", "safari16"],
    minify: true,
    write: false,
    // Inlined into a `<script>`, so a source map would be a comment pointing at a file
    // that does not exist.
    sourcemap: false,
  });

  const script = bundled.outputFiles[0]?.text ?? "";
  if (!script) throw new Error("UI bundle came back empty");

  const shell = readFileSync(path.join(src, "ui/index.html"), "utf8");
  const marker =
    '<script type="module">\n      /* replaced at build time with the bundled app */\n    </script>';

  if (!shell.includes(marker)) {
    throw new Error(
      "The script placeholder is not in ui/index.html; the shell and this script have drifted.",
    );
  }

  // `</script>` inside the bundle would end the tag early. esbuild will not emit one from
  // this source, but a future string literal could, and the failure would look like a
  // broken panel rather than a broken build.
  if (script.includes("</script")) {
    throw new Error(
      "Bundle contains a closing script tag; inlining it would break the document.",
    );
  }

  const html = shell.replace(
    marker,
    `<script type="module">${script}</script>`,
  );

  // Written unformatted, then handed to biome by the `build` script — the same
  // arrangement `catalogue:snapshot` uses for its generated file. The alternative is a
  // repo where `pnpm lint` fails immediately after `pnpm build`, which is how a lint
  // failure stops meaning anything.
  writeFileSync(
    path.join(src, "ui.generated.ts"),
    [
      "// Generated by `pnpm --filter @terrablox/mcp-server build`. Do not edit by hand.",
      "//",
      "// The stack review panel: `src/ui/index.html` with `src/ui/app.ts` bundled into it.",
      "// Committed so that `tsc --noEmit` and the server bundle have it without a build",
      "// step having run first — the same reason the module catalogue is committed.",
      "",
      `export const APP_HTML = ${JSON.stringify(html)};`,
      "",
    ].join("\n"),
    "utf8",
  );

  return html.length;
}

/** The server: the whole workspace graph flattened into one executable file. */
async function buildServer() {
  const result = await build({
    bundle: true,
    entryPoints: [path.join(src, "bin.ts")],
    format: "esm",
    outfile: path.join(here, "dist/bin.js"),
    platform: "node",
    target: "node22",
    // Kept readable on purpose: this file runs on other people's machines, and a stack
    // trace from a minified bundle is not something anyone can report usefully.
    minify: false,
    sourcemap: true,
    // A shebang, so the `bin` entry works when a host execs it directly rather than
    // through `node`. `createRequire` because some dependencies still reach for it, and
    // an ESM bundle has no `require` of its own.
    banner: {
      js: [
        "#!/usr/bin/env node",
        'import { createRequire as __createRequire } from "node:module";',
        "const require = __createRequire(import.meta.url);",
      ].join("\n"),
    },
    logLevel: "warning",
  });

  if (result.errors.length > 0) throw new Error("Server bundle failed");
}

const htmlBytes = await buildUi();
await buildServer();

// stderr, not stdout: nothing may write to stdout in this package's world except JSON-RPC,
// and a build script that breaks that habit is how the habit gets broken.
process.stderr.write(
  `panel ${(htmlBytes / 1024).toFixed(1)} KB, server bundled\n`,
);
